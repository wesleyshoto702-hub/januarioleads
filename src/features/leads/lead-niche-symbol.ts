/** Canonical aliases first, then known historical CRM labels, otherwise neutral. */
export function leadNicheSymbol(segment:string|null|undefined):LeadNicheSymbol {
  const value=(segment??"").trim();
  if(!value)return "Building2";
  const canonical=resolveSearchSegment(value);
  if(canonical) return LEAD_NICHE_SYMBOLS[canonical as keyof typeof LEAD_NICHE_SYMBOLS]??"Building2";
  const normalized=normalizeSearchText(value);
  const known=BY_NORMALIZED.get(normalized);
  if(known)return known;
  if(/sobrancelh|design de sobranc/.test(normalized))return "Flower2";
  if(/chaveiro|chaves/.test(normalized))return "KeyRound";
  if(/barbei|barber/.test(normalized))return "Scissors";
  if(/academia|fitness|musculac|treinamento|personal trainer/.test(normalized))return "Dumbbell";
  if(/dentista|odontolog/.test(normalized))return "Smile";
  if(/clinica|medic|hospital/.test(normalized))return "Stethoscope";
  if(/restaurante|alimentac/.test(normalized))return "UtensilsCrossed";
  if(/cabeleireir|salao de beleza/.test(normalized))return "Scissors";
  if(/veterin|pet shop/.test(normalized))return "PawPrint";
  if(/oficina|mecanica|automotiv/.test(normalized))return "Wrench";
  if(/imobiliar/.test(normalized))return "House";
  if(/informatica|software|tecnolog/.test(normalized))return "Laptop";
  if(/escola|educac/.test(normalized))return "BookOpen";
  const sector=SECTOR_SYMBOLS[Object.keys(SECTOR_SYMBOLS).find(k=>normalizeSearchText(k)===normalized)??""];
  return sector??"Building2";
}
