export function leadNicheEmoji(segment:string | null | undefined):string {
  const label=(segment??"").trim();
  if(!label)return "🏢";
  const canonical=resolveSearchSegment(label);
  if(canonical)return LEAD_NICHE_EMOJI[canonical]??"🏢";
  const key=normalizeSearchText(label);
  const exact=EMOJI_BY_NORMALIZED.get(key);
  if(exact)return exact;
  // Previously imported/manual lead categories may not match the modern
  // catalog exactly. Only clear category words get a specific fallback.
  if(/barbei|barber/.test(key))return "🧔";
  if(/academia|fitness|musculac|treinamento|personal trainer/.test(key))return "🏋️";
  if(/chaveiro|chaves/.test(key))return "🔑";
  if(/sobrancelha/.test(key))return "👁️";
  if(/odont|dentist/.test(key))return "🦷";
  if(/restaurante|comida|aliment/.test(key))return "🍽️";
  if(/cabeleireir|salao de beleza/.test(key))return "💇";
  if(/veterin|pet shop/.test(key))return "🐾";
  if(/mecanica|oficina|automotiv/.test(key))return "🔧";
  if(/imobiliar|corretor de imoveis/.test(key))return "🏠";
  if(/farmacia|drogaria/.test(key))return "💊";
  if(/tecnolog|informat|software/.test(key))return "💻";
  if(/escola|educa/.test(key))return "📚";
  const group=SEGMENT_GROUPS.find(g=>
    g.items.some(item=>normalizeSearchText(item)===key) ||
    normalizeSearchText(g.label)===key
  );
  return group?SECTOR_EMOJI[group.label]??"🏢":"🏢";
}
