/** Narrow name filter for categories shared by different specialties. */
const NAME_FILTERS: Record<string, RegExp> = {
  "Barbearia": /\\b(barbearia|barber|barbeiro)\\b/i,
  "Salão de Beleza": /\\b(salao|salão|cabeleireir|hair|beleza)\\b/i,
};

export function geoapifyCategoryForSegment(value: string): {
  segment: string;
  categories: readonly string[];
  nameFilter: RegExp | null;
} | null {
  const canonical = resolveSearchSegment(value);
  if (!canonical) return null;
  const categories = GEOAPIFY_CATEGORIES[canonical];
  if (!categories?.length) return null;
  return { segment: canonical, categories, nameFilter: NAME_FILTERS[canonical] ?? null };
}

/** Pure self-check for the future public launch and catalog changes. */
export function validateGeoapifyCoverage() {
  const names = SEGMENT_GROUPS.flatMap(group => group.items);
  return names.length === 196 &&
    names.every(name => Object.hasOwn(GEOAPIFY_CATEGORIES,name)) &&
    Object.keys(GEOAPIFY_CATEGORIES).every(name=>names.includes(name));
}
