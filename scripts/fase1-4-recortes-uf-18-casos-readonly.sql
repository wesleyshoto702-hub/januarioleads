FROM samples s CROSS JOIN (VALUES('old'),('prepared')) v(version)
LEFT JOIN grouped g ON g.state=s.state AND g.city_key=s.city_key AND g.niche=s.niche AND g.version=v.version
ORDER BY s.state,s.city_key,s.niche,v.version;
