SELECT count(*)::bigint AS total,
 count(*) FILTER(WHERE nullif(btrim(name),'') IS NULL)::bigint AS missing_name,
 count(*) FILTER(WHERE length(btrim(name))<3)::bigint AS short_names,
 count(*) FILTER(WHERE nullif(btrim(category),'') IS NULL)::bigint AS missing_category,
 count(*) FILTER(WHERE nullif(btrim(address),'') IS NULL)::bigint AS missing_address,
 count(*) FILTER(WHERE latitude IS NULL OR longitude IS NULL)::bigint AS missing_coordinates,
 count(*) FILTER(WHERE latitude NOT BETWEEN -35 AND 6 OR longitude NOT BETWEEN -75 AND -30)::bigint AS outside_rough_brazil_bbox,
 count(*) FILTER(WHERE nullif(btrim(phone),'') IS NOT NULL)::bigint AS phones,
 count(*) FILTER(WHERE length(regexp_replace(coalesce(phone,''),'\D','','g')) BETWEEN 10 AND 13)::bigint AS plausible_phone_length,
 count(*) FILTER(WHERE nullif(btrim(email),'') IS NOT NULL)::bigint AS emails,
 count(*) FILTER(WHERE btrim(coalesce(email,'')) ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')::bigint AS plausible_email_syntax,
 count(*) FILTER(WHERE nullif(btrim(website),'') IS NOT NULL)::bigint AS websites,
 count(*) FILTER(WHERE website ~* '^https?://[^/.[:space:]]+(\.[^/[:space:]]+)+')::bigint AS plausible_web_url,
