-- Q5: Selected location concentration; totals by city rather than search results
WITH bycity AS(SELECT state,city_key,count(*) n FROM public.overture_places GROUP BY 1,2)
SELECT count(*) AS cities,
 min(n) AS fewest_places_in_city,max(n) AS most_places_in_city,
 round(avg(n),2) AS mean_places_in_city,
 percentile_cont(0.5) WITHIN GROUP(ORDER BY n) AS median_places_in_city,
 count(*) FILTER(WHERE n=60) AS exactly_60_places,
 count(*) FILTER(WHERE n<=10) AS cities_with_10_or_fewer
FROM bycity;

