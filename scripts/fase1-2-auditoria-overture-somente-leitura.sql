FROM public.overture_places;

-- Q2: Potentially duplicate business labels, NOT auto-removal candidates
WITH by_name AS(
 SELECT state,city_key,name_key,count(*) n,
 count(DISTINCT concat_ws(':',round(latitude::numeric,5)::text,round(longitude::numeric,5)::text)) coords_rough
 FROM public.overture_places
 WHERE nullif(btrim(name_key),'') IS NOT NULL
 GROUP BY 1,2,3 HAVING count(*)>1
), by_address AS(
 SELECT state,city_key,name_key,lower(btrim(address)) addr,count(*) n
 FROM public.overture_places
 WHERE nullif(btrim(name_key),'') IS NOT NULL AND nullif(btrim(address),'') IS NOT NULL
 GROUP BY 1,2,3,4 HAVING count(*)>1
)
SELECT
 (SELECT count(*) FROM by_name) AS repeated_name_city_groups,
 (SELECT coalesce(sum(n),0) FROM by_name) AS rows_in_repeated_name_city_groups,
 (SELECT count(*) FROM by_name WHERE coords_rough>1) AS distinct_approx_coord_groups,
 (SELECT count(*) FROM by_address) AS repeated_name_address_groups,
 (SELECT coalesce(sum(n),0) FROM by_address) AS rows_in_repeated_name_address_groups;

-- Q3: Shared contacts (can be legitimate networks / franchises / service desks)
WITH ph AS(
 SELECT regexp_replace(phone,'\D','','g') contact,count(*) n,
 count(DISTINCT state||'|'||city_key) cities, count(DISTINCT name_key) names
 FROM public.overture_places WHERE nullif(btrim(phone),'') IS NOT NULL GROUP BY 1
), em AS(
 SELECT lower(btrim(email)) contact,count(*) n,
 count(DISTINCT state||'|'||city_key) cities, count(DISTINCT name_key) names
 FROM public.overture_places WHERE nullif(btrim(email),'') IS NOT NULL GROUP BY 1
)
SELECT
 (SELECT count(*) FROM ph WHERE n>1) AS reused_phone_groups,
 (SELECT coalesce(sum(n),0) FROM ph WHERE n>1) AS rows_with_reused_phones,
 (SELECT count(*) FROM ph WHERE n>=10) AS phone_groups_10plus,
 (SELECT coalesce(sum(n),0) FROM ph WHERE n>=10) AS rows_phone_10plus,
 (SELECT max(n) FROM ph) AS highest_phone_reuse,
 (SELECT count(*) FROM em WHERE n>1) AS reused_email_groups,
 (SELECT coalesce(sum(n),0) FROM em WHERE n>1) AS rows_with_reused_emails,
 (SELECT count(*) FROM em WHERE n>=10) AS email_groups_10plus,
 (SELECT max(n) FROM em) AS highest_email_reuse;

