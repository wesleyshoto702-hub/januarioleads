), locations AS (
 SELECT DISTINCT state,city_key FROM public.overture_places
 WHERE state IS NOT NULL AND city_key IS NOT NULL
), grouped AS (
 SELECT m.version,m.niche,p.state,p.city_key,
  count(*)::integer AS candidates,
  count(*) FILTER(WHERE length(regexp_replace(coalesce(p.phone,''),'[^0-9]','','g'))
     BETWEEN 10 AND 13)::integer AS plausible_phones
 FROM public.overture_places p JOIN mapping m ON p.category=m.category
 WHERE p.state IS NOT NULL AND p.city_key IS NOT NULL
  AND nullif(btrim(p.name),'') IS NOT NULL
  AND p.operating_status IS DISTINCT FROM 'permanently_closed'
 GROUP BY m.version,m.niche,p.state,p.city_key
), per_niche AS (
 SELECT version,niche,
  count(*)::integer AS cities_with_any,
  count(*) FILTER (WHERE candidates>=8 AND plausible_phones>=5)::integer AS cities_with_more,
  count(*) FILTER (WHERE NOT(candidates>=8 AND plausible_phones>=5))::integer AS cities_limited,
  sum(candidates)::bigint AS candidate_memberships,
  sum(plausible_phones)::bigint AS plausible_phone_memberships,
  max(candidates)::integer AS largest_city_niche
 FROM grouped GROUP BY version,niche
), city_total AS (SELECT count(*)::integer AS total_cities FROM locations)
SELECT v.version,n.niche,c.total_cities,
